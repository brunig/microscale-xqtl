#!/bin/bash
# Run ON HOFFMAN2 as a batch job:   qsub tools/zenodo_package.sh
# Builds the Zenodo data record's files in $STAGE. Reads only; writes nothing
# inside the project. Upload afterwards with tools/zenodo_upload.sh.
#$ -cwd
#$ -o zenodo_package.log
#$ -j y
#$ -l h_rt=8:00:00,h_data=4G
#$ -pe shared 4
set -euo pipefail
P=/u/project/kruglyak/bruni/projects/xQTLpaper
REF=/u/project/kruglyak/PUBLIC_SHARED/yeast/reference
STAGE=${STAGE:-$SCRATCH/xqtl_zenodo}
mkdir -p "$STAGE"; cd "$P"
GZ=$(command -v pigz >/dev/null && echo "pigz -p 4" || echo gzip)
pack() { local out=$1; shift; echo "$(date +%T) $out"; tar cf - "$@" | $GZ > "$STAGE/$out"; }

## 1. the two run directories, without the .qs caches (regenerated by the driver)
pack runs_v7.tar.gz --exclude='runs/v7/cache' runs/v7
pack runs_v6.tar.gz --exclude='runs/v6/cache' runs/v6

## 2. per-sample allele counts: the driver's primary input, one file per well
pack count_files.tar.gz count_files

## 3. the other lab-made inputs the driver reads (hoffman2 path block, lines 560-579)
mkdir -p "$STAGE/inputs"
cp -p files/flatkey_A1.csv files/Z_final.qs "$STAGE/inputs/"
cp -p "$REF/3000/VCFs_SNPs/variant_lookup.qs" "$STAGE/inputs/"
cp -p "$REF/yeast_ref/saccharomyces_cerevisiae.gff.gz" "$STAGE/inputs/"
pack qc.tar.gz qc                       # sample_allowlist.csv, unresolved_wells_A1.txt, QC tables
( cd "$STAGE" && tar cf - inputs | $GZ > driver_inputs.tar.gz && rm -r inputs )

## 4. every input, with its checksum; third-party files are cited, not redistributed
{
  printf 'path\tmd5\tbytes\tdeposited\n'
  for f in files/flatkey_A1.csv files/Z_final.qs \
           "$REF/3000/VCFs_SNPs/variant_lookup.qs" \
           "$REF/yeast_ref/saccharomyces_cerevisiae.gff.gz" \
           qc/sample_allowlist.csv qc/unresolved_wells_A1.txt; do
    printf '%s\t%s\t%s\tyes\n' "$f" "$(md5sum < "$f" | cut -d' ' -f1)" "$(stat -c %s "$f")"
  done
  for f in "$REF/3000/full3039Matrix.CNVnatorResults.tsv" \
           "$REF/fungAMR/41564_2025_2084_MOESM3_ESM.xlsx" \
           files/gene_association_R64-5-1_20240529.sgd files/go-basic.obo; do
    printf '%s\t%s\t%s\tno: cite source\n' "$f" "$(md5sum < "$f" | cut -d' ' -f1)" "$(stat -c %s "$f")"
  done
} > "$STAGE/INPUTS.tsv"

## 5. checksums of what will be uploaded
cd "$STAGE" && md5sum *.tar.gz INPUTS.tsv > MD5SUMS.txt
du -sh "$STAGE"/*; echo "$(date +%T) done: $STAGE"
